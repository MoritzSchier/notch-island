/// Sprache der App: Deutsch oder Englisch (Einstellungen › Allgemein, Einrichtungsassistent).
/// Texte stehen im Code auf Deutsch; `tr("…")` liefert bei Englisch die Übersetzung aus `Loc.english`.
enum Loc {
    static let key = "appLanguage"   // "de", "en" oder "system"

    static var current: String {
        let v = UserDefaults.standard.string(forKey: key) ?? "system"
        if v == "de" || v == "en" { return v }
        let pref = Locale.preferredLanguages.first?.lowercased() ?? "en"
        return pref.hasPrefix("de") ? "de" : "en"
    }

    static var isGerman: Bool { current == "de" }
    static var locale: Locale { Locale(identifier: isGerman ? "de_DE" : "en_US") }

    static func translate(_ key: String) -> String? {
        isGerman ? nil : english[key]
    }
}

/// Text mit Platzhaltern: aus "Noch \(n) Min" wird der Schlüssel "Noch %@ Min" plus die Werte.
struct LocString: ExpressibleByStringInterpolation {
    var key = ""
    var args: [String] = []

    init(stringLiteral value: String) { key = value }

    init(stringInterpolation: Interpolation) {
        key = stringInterpolation.key
        args = stringInterpolation.args
    }

    struct Interpolation: StringInterpolationProtocol {
        var key = ""
        var args: [String] = []
        init(literalCapacity: Int, interpolationCount: Int) {}
        mutating func appendLiteral(_ literal: String) { key += literal.replacingOccurrences(of: "%", with: "%%") }
        mutating func appendInterpolation<T>(_ value: T) {
            key += "%@"
            args.append(String(describing: value))
        }
    }

    var resolved: String {
        var template = key
        if let t = Loc.translate(key) { template = t }
        // %@ der Reihe nach füllen, %% → %
        var out = ""
        var i = template.startIndex
        var argIndex = 0
        while i < template.endIndex {
            let c = template[i]
            let next = template.index(after: i)
            if c == "%", next < template.endIndex {
                let n = template[next]
                if n == "@" {
                    out += argIndex < args.count ? args[argIndex] : ""
                    argIndex += 1
                    i = template.index(after: next); continue
                }
                if n == "%" { out += "%"; i = template.index(after: next); continue }
            }
            out.append(c)
            i = next
        }
        return out
    }
}

/// Übersetzt einen Oberflächentext (Deutsch im Code → Englisch, falls gewählt)
func tr(_ s: LocString) -> String { s.resolved }

